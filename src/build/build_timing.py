#!/usr/bin/env python
"""What the reproduction pipeline COSTS: each builder's own wall time.

The package can be rebuilt from the immutable downloads by committed scripts -
that is the reproducibility gate - but until now nothing recorded how long any
of it takes. A pipeline whose cost is unknown cannot be budgeted, cannot be
scheduled against an arm, and cannot tell a slow step from a hung one.

WHERE THE NUMBER GOES, AND WHY NOT WHERE IT WOULD BE HANDIEST. A wall time is
the one quantity that is different on every run of the same inputs. Put it in
a file the manifest hashes - a builder's own `_*_report.json`, or a column in
`MANIFEST.csv` - and two builds of identical content stop producing identical
bytes, which is exactly the defect `det_io.py` exists to prevent for gzip and
zip headers. A previous session refused a manifest column for that reason
(9.156), and a report is no safer: the committed reports ARE manifest rows
with recorded digests.

So the timing lands in ONE roll-up beside the manifest, at
`cities/<city>/data/_build_timing.json`, which the manifest's own scan does
not cover (`SCAN` in build_manifest.py lists `data/raw` and `data/processed`,
never `data/` itself) and `.gitignore` excludes. Nothing hashed moves.

USAGE - one line in a builder, at the top of its `__main__` block:

    import build_timing as _timing
    ...
    if __name__ == '__main__':
        _timing.start(__file__)
        main()

`start()` registers an `atexit` hook, so the entry is written whether the
builder returns, raises or calls `sys.exit`, and the recorded `status` says
which. Each builder owns its own entry; the roll-up is read, updated and
rewritten, so builders run one at a time or in any order accumulate rather
than overwrite.

City-agnostic: the location comes from `city.py` and nothing here names a
city, a builder or an artefact.
"""
import atexit
import datetime
import io
import json
import os
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, '..'))
import city as _city  # noqa: E402

REPO = os.path.abspath(os.path.join(_HERE, '..', '..'))
FILENAME = '_build_timing.json'


def path():
    """The roll-up's location - beside the manifest, outside its scan."""
    return _city.path('data', FILENAME)


def script_key(script):
    """A builder's repo-relative path, the same key the manifest's
    `produced_by` column uses, so the two join."""
    try:
        rel = os.path.relpath(os.path.abspath(script), REPO)
    except ValueError:                       # different drive on Windows
        return os.path.basename(script)
    return rel.replace(os.sep, '/')


def read():
    try:
        with io.open(path(), encoding='utf-8') as f:
            doc = json.load(f)
    except (OSError, ValueError):
        return {}
    entries = doc.get('builders')
    return entries if isinstance(entries, dict) else {}


def record(script, seconds, status='ok'):
    """Merge one builder's wall time into the roll-up.

    The entry is keyed by the builder's repo-relative path and carries the
    elapsed seconds, when it was recorded and how the run ended. Written with
    sorted keys and LF newlines so a rebuild produces the same file except
    for the numbers that genuinely moved.
    """
    entries = read()
    entries[script_key(script)] = dict(
        seconds=round(float(seconds), 3),
        status=status,
        recorded=datetime.datetime.now().replace(microsecond=0).isoformat())
    doc = dict(
        note=('Wall time per builder. NOT part of the data package and NOT '
              'hashed: a wall time differs on every build, and a manifest row '
              'must not. Regenerated by src/build/build_timing.py.'),
        city=_city.CITY,
        builders=dict(sorted(entries.items())),
        total_seconds=round(sum(e.get('seconds') or 0.0
                                for e in entries.values()), 3))
    dest = path()
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with io.open(dest, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(doc, f, indent=2, sort_keys=False)
        f.write('\n')
    return doc


def start(script):
    """Start this builder's clock and record the elapsed time when it ends,
    however it ends. Safe to call more than once; the first call wins."""
    if getattr(start, '_started', None) == script_key(script):
        return
    start._started = script_key(script)
    t0 = time.time()

    def _finish():
        status = 'ok'
        exc = sys.exc_info()[0]
        if exc is not None and exc is not SystemExit:
            status = 'failed'
        try:
            record(script, time.time() - t0, status)
        except OSError:
            pass                              # never fail a build over timing

    atexit.register(_finish)


class timed(object):                          # noqa: N801  (used as a verb)
    """Context-manager form, for a caller that runs a builder in-process."""

    def __init__(self, script):
        self.script = script
        self.t0 = None

    def __enter__(self):
        self.t0 = time.time()
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            record(self.script, time.time() - self.t0,
                   'ok' if exc_type is None or exc_type is SystemExit
                   else 'failed')
        except OSError:
            pass
        return False


def report(stream=None):
    """Print the roll-up, slowest first - the reproduction pipeline's cost."""
    stream = stream or sys.stdout
    entries = read()
    if not entries:
        stream.write('no build timing recorded yet (%s)\n' % path())
        return 0
    total = sum(e.get('seconds') or 0.0 for e in entries.values())
    stream.write('build timing, %d builder(s), %.1f s total (%.2f h)\n'
                 % (len(entries), total, total / 3600.0))
    for key, e in sorted(entries.items(),
                         key=lambda kv: -(kv[1].get('seconds') or 0.0)):
        stream.write('  %9.1f s  %-8s %s\n'
                     % (e.get('seconds') or 0.0, e.get('status') or '', key))
    return 0


if __name__ == '__main__':
    sys.exit(report())
